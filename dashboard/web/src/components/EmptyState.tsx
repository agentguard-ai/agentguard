/**
 * EmptyState — Displays a contextual placeholder when a panel has no data.
 *
 * Visual treatment:
 * - Dashed border to distinguish from SkeletonLoader (which uses pulsing animation)
 * - Muted colors (text-secondary, bg-tertiary) to distinguish from error boundary (red/danger)
 * - Centered icon and message for a clear "no data" indication
 *
 * Requirements: 14.1, 14.2, 14.3
 */
